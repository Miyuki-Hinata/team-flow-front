// ============================================================
// theme.ts — TeamFlow デザイントークン（辞書）
// ============================================================
// アプリ全体で使う「値」を、ここ1箇所に集約する。
// styled-components の中から props.theme.colors.xxx のように呼び出して使う。
// → 色や余白を変えたいときは、このファイルだけ直せば全画面に反映される。）
// ============================================================

// ------------------------------------------------------------
// 1. モードに依存しない値（余白・角丸・フォント）
//    ライトモードでもダークモードでも共通で使う値。
//    色だけがモードで変わるので、色は後で別に定義する。
// ------------------------------------------------------------

// 余白：8の倍数を基準にする（業界標準）。値をバラバラにせず統一感を出すため。
// ※余白は px のまま。理由：余白は「文字サイズに連動して伸び縮みさせない方が、
//   レイアウトが安定する」ため。文字（rem）と余白（px）で役割を分けるのは定石。
const spacing = {
  xs: '4px',    // ごく狭い隙間（アイコンと文字の間など）
  sm: '8px',    // 狭い余白
  md: '16px',   // 標準の余白（最もよく使う）
  lg: '24px',   // 広い余白（セクション間など）
  xl: '32px',   // とても広い余白（ページ上下など）
  xxl: '48px',  // 特に大きく空けたいとき
} as const;

// ブレークポイント：画面幅で「レイアウトを切り替える」境界。
// 例：この幅以下ならサイドバーを隠す、横並びを縦積みにする、など。
// 定石の値を採用（スマホ / タブレット / PC の一般的な境界）。
// 使い方：各コンポーネントで「@media (min-width: ...)」のように参照する。
const breakpoints = {
  sm: '640px',   // これ以上 = 大きめスマホ〜
  md: '768px',   // これ以上 = タブレット〜
  lg: '1024px',  // これ以上 = PC〜
  xl: '1280px',  // これ以上 = 大画面PC〜
} as const;

// 角丸：8pxを標準に。
// こちらもremで指定（px ÷ 16 = rem）。
const radius = {
  sm: '0.25rem',  // 4px：タグ・バッジなど小さい要素
  md: '0.5rem',   // 8px：標準（ボタン・入力欄）
  lg: '0.75rem',  // 12px：カードなど大きい要素
  full: '9999px', // 完全な円・ピル形（アバターなど）。これは固定でOK
} as const;

// フォントサイズ：本文16pxを基準に段階を作る。小さすぎる文字を避け、長時間でも疲れにくく。
// 単位は rem を使う（px ÷ 16 = rem）。
// → remは「ブラウザの基準文字サイズ」に対する相対指定。
//   ユーザーがブラウザ設定で文字を大きくすると、これらも追従して拡大する（アクセシビリティ対応）。
//   pxだと固定されてしまい、ユーザー設定を無視してしまう。
const fontSize = {
  xs: '0.75rem',   // 12px：補足・キャプション
  sm: '0.875rem',  // 14px：やや小さい本文・ラベル
  md: '1rem',      // 16px：標準の本文（基準）
  lg: '1.125rem',  // 18px：小見出し
  xl: '1.375rem',  // 22px：見出し
  xxl: '1.75rem',  // 28px：大見出し・ページタイトル
} as const;

// 行間：本文は広めに取り、読みやすく（医療現場で長文の申し送りなども読むため）。
const lineHeight = {
  tight: 1.3,   // 見出し用（詰める）
  normal: 1.6,  // 本文用（ゆったり）
} as const;

// フォントの太さ：2種類だけに絞る。多用すると重く見えるため（400=通常 / 600=強調）。
const fontWeight = {
  normal: 400,
  bold: 600,
} as const;

// ------------------------------------------------------------
// 2. セマンティックカラー（意味を持つ色）
//    モードに依存せず共通。状態を一目で伝える色。
//    緑=完了 / 黄=注意 / 赤=緊急 / 青=情報（看護現場の色トリアージを反映）
//    各色は「濃い本体色」と「薄い背景色」をペアで持つ。
//    （例：緊急タグは bg=薄い赤、text=濃い赤）
// ------------------------------------------------------------
const semantic = {
  success: { main: '#3B6D11', bg: '#EAF3DE' }, // 緑：完了・正常
  warning: { main: '#854F0B', bg: '#FAEEDA' }, // 黄：注意・期限が近い
  danger:  { main: '#A32D2D', bg: '#FCEBEB' }, // 赤：緊急・エラー
  info:    { main: '#185FA5', bg: '#E6F1FB' }, // 青：情報・通知
} as const;

// ------------------------------------------------------------
// 3. ブランドカラー（アプリの基調色）
//    濃紺2色を土台、ティールをアクセントに。
//    モードに依存しない「ブランドの軸」として定義。
// ------------------------------------------------------------
const brand = {
  navyDeep: '#00072D',  // 極濃紺：サイドバーなど最も深い土台
  navy:     '#001F5B',  // 濃紺：ヘッダーなど
  teal:     '#0E9384',  // ティール：主要ボタン・アクセント（押してほしい操作）
  tealDark: '#0B6B60',  // ティール濃いめ：ホバー時など
} as const;

// colors の中（brand や semantic と並べる位置）に追加
// 患者アイコン用の色（性別を色で表す。1色1意味）
const patientIcon = {
  male:    { main: '#185FA5', bg: '#E6F1FB' },  // 男性：青（線＋薄い青背景）
  female:  { main: '#9333A8', bg: '#F3EAF6' },  // 女性：紫（線＋薄い紫背景）
  unknown: { main: '#9298A6', bg: '#EEF0F4' },  // 不明：グレー（中立。青でも紫でもない）
} as const;

// ------------------------------------------------------------
// 4. ライトモードの色
//    背景・文字・枠線など、モードで変わる色をまとめる。
// ------------------------------------------------------------
const lightColors = {
  brand,      // ブランド色（共通）
  semantic,   // 意味の色（共通）
  patientIcon, // 患者アイコン（共通）

  // 背景：3段階。奥から手前へ surface0 → surface2
  surface: {
    base: '#F7F8FA',   // ページ全体の背景（ほんのり灰色で目に優しい。真っ白を避ける）
    raised: '#FFFFFF', // カードなど一段持ち上がった面
    sunken: '#EEF0F4', // 一段沈んだ面（入力欄の背景など）
  },

  // 文字：濃淡3段階。主要→補助→ヒントの順に薄くする。
  text: {
    primary: '#1A1D24',   // 主要な文字（真っ黒より少し柔らかい濃色）
    secondary: '#5A6072', // 補助的な文字（説明文など）
    muted: '#9298A6',     // ヒント・プレースホルダー
    onBrand: '#FFFFFF',   // ブランド色の上に乗せる文字（濃紺ヘッダー上の白文字など）
  },

  // 枠線：通常とホバー時で濃さを変える。
  border: {
    default: '#E2E5EB', // 標準の枠線（うっすら）
    strong: '#C5CAD4',  // 強調・ホバー時
  },
} as const;

// ------------------------------------------------------------
// 5. ダークモードの色
//    背景を暗く、文字を明るく反転。ブランド色と意味の色は共通のまま。
//    ※長時間画面を見る医療現場のために用意（目の疲労軽減）
// ------------------------------------------------------------
const darkColors = {
  brand,
  semantic,
  patientIcon,

  surface: {
    base: '#0D1117',   // ページ全体の背景（暗い。GitHubのダークに近い）
    raised: '#161B22', // カードなど（少し明るい暗色）
    sunken: '#0A0D12', // 沈んだ面
  },

  text: {
    primary: '#E6E8EB',   // 主要な文字（明るいグレー。真っ白は眩しいので避ける）
    secondary: '#A0A6B0', // 補助
    muted: '#6B7280',     // ヒント
    onBrand: '#FFFFFF',   // ブランド色の上の文字
  },

  border: {
    default: '#2A2F3A',
    strong: '#3D4350',
  },
} as const;

// ------------------------------------------------------------
// 6. テーマを組み立てる
//    共通の値（spacing等）と、モード別の色（lightColors/darkColors）を合体。
//    themeLight と themeDark の2つを作り、アプリ側で切り替える。
// ------------------------------------------------------------
const base = { spacing, radius, fontSize, fontWeight, lineHeight, breakpoints };

export const themeLight = { ...base, colors: lightColors } as const;
export const themeDark = { ...base, colors: darkColors } as const;

// テーマの「型」を定義（TypeScriptの恩恵：theme.colors.xxx を補完・型チェックできる）
export type Theme = typeof themeLight;